#!/usr/bin/env python3
"""Write firmware/src/secrets.h for ESP URL update (gitignored)."""

from __future__ import annotations

import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SECRETS_PATH = REPO_ROOT / "firmware" / "src" / "secrets.h"
ENV_PATH = REPO_ROOT / ".env"


def _load_dotenv() -> None:
    if not ENV_PATH.is_file():
        return
    for line in ENV_PATH.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        os.environ.setdefault(key, value)


_load_dotenv()

API_BASE = os.getenv("API_PUBLIC_BASE_URL", "https://192.168.0.181").rstrip("/")
INGEST_URL = os.getenv("DEVICE_INGEST_BASE_URL", "").strip().rstrip("/")
if not INGEST_URL:
    INGEST_URL = API_BASE.replace("https://", "http://")
INGEST_URL = INGEST_URL + "/api/v1/ingest"

ADMIN_LOGIN = os.getenv("ADMIN_LOGIN", "admin")
ADMIN_PASSWORD = os.getenv("ADMIN_PASSWORD", "admin")


def _request(method: str, path: str, body: dict | None = None, token: str | None = None) -> object:
    url = f"{API_BASE}{path}"
    headers = {"Content-Type": "application/json"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    data = None if body is None else json.dumps(body).encode()
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    ctx = urllib.request.ssl._create_unverified_context()  # self-signed LAN TLS
    with urllib.request.urlopen(req, context=ctx, timeout=15) as resp:
        return json.loads(resp.read().decode())


def main() -> None:
    login = _request(
        "POST",
        "/api/v1/auth/login",
        {"login": ADMIN_LOGIN, "password": ADMIN_PASSWORD},
    )
    access_token = login["access_token"]
    sensors = _request("GET", "/api/v1/sensors", token=access_token)
    if not sensors:
        print("No sensors in database — create one in admin UI first", file=sys.stderr)
        sys.exit(1)

    sensor = sensors[0]
    prov = _request(
        "GET",
        f"/api/v1/sensors/{sensor['id']}/provisioning-token",
        token=access_token,
    )
    device_token = prov["api_token"]
    ingest_url = prov.get("ingest_url", INGEST_URL)

    content = f"""#pragma once
// Auto-generated by tools/prepare_esp_secrets.py — do not commit

#define HC_SERVER_URL "{ingest_url}"
#define HC_DEVICE_TOKEN "{device_token}"
"""
    SECRETS_PATH.write_text(content, encoding="utf-8")
    print(f"Wrote {SECRETS_PATH}")
    print(f"ingest_url: {ingest_url}")
    print(f"sensor: {sensor.get('name')} (id={sensor['id']})")


if __name__ == "__main__":
    try:
        main()
    except urllib.error.HTTPError as exc:
        print(f"API error: {exc.code} {exc.read().decode()}", file=sys.stderr)
        sys.exit(1)
    except urllib.error.URLError as exc:
        print(f"Connection error: {exc.reason}", file=sys.stderr)
        sys.exit(1)
