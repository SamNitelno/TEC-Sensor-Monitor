//go:embed migrations/*.sql
var migrationsFS embed.FS

// sqlparts holds migrations that must run statement by statement outside a
// transaction with retries (continuous-aggregate refreshes can collide with
// the refresh policy job TimescaleDB starts right after the policy is added).
//
//go:embed sqlparts/*.sql
var sqlPartsFS embed.FS

// gooseTable is goose's default version table name.
const gooseTable = "goose_db_version"

// LatestVersion is the newest schema version shipped with this binary.
const LatestVersion = 14

// Migrate brings the schema to the latest version. A database previously
// managed by Alembic (table alembic_version, revisions "001".."014") is
// adopted first: its applied revisions are recorded as applied goose
// versions, so nothing is executed twice and no data is touched.
func Migrate(ctx context.Context, databaseURL, jwtSecret string, log *slog.Logger) error {
	sqlDB, err := sql.Open("pgx", databaseURL)
	if err != nil {
		return err
	}
	defer sqlDB.Close()

	if err := adoptAlembic(ctx, sqlDB, log); err != nil {
		return fmt.Errorf("adopt alembic history: %w", err)
	}

	sub, err := fs.Sub(migrationsFS, "migrations")
	if err != nil {
		return err
	}
	provider, err := goose.NewProvider(goose.DialectPostgres, sqlDB, sub,
		goose.WithGoMigrations(
			goose.NewGoMigration(2,
				&goose.GoFunc{RunDB: sqlPart("00002_up.sql"), Mode: goose.TransactionDisabled},
				&goose.GoFunc{RunDB: sqlPart("00002_down.sql"), Mode: goose.TransactionDisabled}),
			goose.NewGoMigration(12,
				&goose.GoFunc{RunDB: sqlPart("00012_up.sql"), Mode: goose.TransactionDisabled},
				&goose.GoFunc{RunDB: sqlPart("00012_down.sql"), Mode: goose.TransactionDisabled}),
			goose.NewGoMigration(13,
				&goose.GoFunc{RunTx: deviceTokenHashUp(jwtSecret)},
				&goose.GoFunc{RunTx: deviceTokenHashDown}),
		),
	)
	if err != nil {
		return err
	}
	results, err := provider.Up(ctx)
	for _, r := range results {
		if r.Error == nil {
			log.Info("migration_applied", "version", r.Source.Version, "duration_ms", r.Duration.Milliseconds())
		}
	}
	if err != nil {
		return err
	}
	version, err := provider.GetDBVersion(ctx)
	if err == nil {
		log.Info("schema_ready", "version", version)
	}
	return err
}

func tableExists(ctx context.Context, db *sql.DB, name string) (bool, error) {
	var exists bool
	err := db.QueryRowContext(ctx,
		`SELECT EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = current_schema() AND tablename = $1)`,
		name).Scan(&exists)
	return exists, err
}

func adoptAlembic(ctx context.Context, sqlDB *sql.DB, log *slog.Logger) error {
	hasGoose, err := tableExists(ctx, sqlDB, gooseTable)
	if err != nil || hasGoose {
		return err
	}
	hasAlembic, err := tableExists(ctx, sqlDB, "alembic_version")
	if err != nil || !hasAlembic {
		return err
	}
	var revision string
	if err := sqlDB.QueryRowContext(ctx, `SELECT version_num FROM alembic_version LIMIT 1`).Scan(&revision); err != nil {
		if err == sql.ErrNoRows {
			return nil // empty alembic table: treat as fresh database
		}
		return err
	}
	applied, err := strconv.Atoi(strings.TrimSpace(revision))
	if err != nil || applied < 1 || applied > LatestVersion {
		return fmt.Errorf("unknown alembic revision %q", revision)
	}

	tx, err := sqlDB.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback() }()
	if _, err := tx.ExecContext(ctx, fmt.Sprintf(`CREATE TABLE %s (
		id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL,
		is_applied boolean NOT NULL,
		tstamp timestamp NOT NULL DEFAULT now()
	)`, gooseTable)); err != nil {
		return err
	}
	for v := 0; v <= applied; v++ {
		if _, err := tx.ExecContext(ctx,
			fmt.Sprintf(`INSERT INTO %s (version_id, is_applied) VALUES ($1, true)`, gooseTable), v); err != nil {
			return err
		}
	}
	if err := tx.Commit(); err != nil {
		return err
	}
	log.Info("alembic_history_adopted", "alembic_revision", revision, "goose_version", applied)
	return nil
}

// deviceTokenHashUp ports Alembic 013: add failed_attempts and hash any
// plaintext device tokens with JWT_SECRET as pepper.
func deviceTokenHashUp(pepper string) func(context.Context, *sql.Tx) error {
	return func(ctx context.Context, tx *sql.Tx) error {
		if _, err := tx.ExecContext(ctx,
			`ALTER TABLE contact_verification_batches ADD COLUMN failed_attempts INTEGER DEFAULT '0' NOT NULL`); err != nil {
			return err
		}
		if pepper == "" {
			return nil
		}
		rows, err := tx.QueryContext(ctx, `SELECT id, api_token FROM sensors`)
		if err != nil {
			return err
		}
		type row struct {
			id    int64
			token string
		}
		var pending []row
		for rows.Next() {
			var r row
			if err := rows.Scan(&r.id, &r.token); err != nil {
				rows.Close()
				return err
			}
			if !isHex64(r.token) {
				pending = append(pending, r)
			}
		}
		rows.Close()
		if err := rows.Err(); err != nil {
			return err
		}
		for _, r := range pending {
			sum := sha256.Sum256([]byte(r.token + ":" + pepper))
			if _, err := tx.ExecContext(ctx, `UPDATE sensors SET api_token = $1 WHERE id = $2`,
				hex.EncodeToString(sum[:]), r.id); err != nil {
				return err
			}
		}
		return nil
	}
}

func deviceTokenHashDown(ctx context.Context, tx *sql.Tx) error {
	_, err := tx.ExecContext(ctx, `ALTER TABLE contact_verification_batches DROP COLUMN failed_attempts`)
	return err
}

// splitStatements splits a migration file on ";" at line ends and drops
// comment-only chunks (the parts files contain no function bodies).
func splitStatements(sqlText string) []string {
	var out []string
	var cur strings.Builder
	for _, line := range strings.Split(sqlText, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "--") || trimmed == "" {
			continue
		}
		cur.WriteString(line)
		cur.WriteByte('\n')
		if strings.HasSuffix(trimmed, ";") {
			out = append(out, strings.TrimSpace(cur.String()))
			cur.Reset()
		}
	}
	if s := strings.TrimSpace(cur.String()); s != "" {
		out = append(out, s)
	}
	return out
}

// sqlPart runs an embedded file outside a transaction; continuous-aggregate
// refreshes are retried while a concurrent (policy) refresh holds the lock.
func sqlPart(name string) func(context.Context, *sql.DB) error {
	return func(ctx context.Context, db *sql.DB) error {
		data, err := sqlPartsFS.ReadFile("sqlparts/" + name)
		if err != nil {
			return err
		}
		for _, stmt := range splitStatements(string(data)) {
			for attempt := 0; ; attempt++ {
				_, err = db.ExecContext(ctx, stmt)
				if err == nil {
					break
				}
				var pgErr *pgconn.PgError
				if errors.As(err, &pgErr) && pgErr.Code == "55P03" && attempt < 60 {
					select {
					case <-ctx.Done():
						return ctx.Err()
					case <-time.After(500 * time.Millisecond):
					}
					continue
				}
				return fmt.Errorf("%s: %w\n%s", name, err, stmt)
			}
		}
		return nil
	}
}

func isHex64(s string) bool {
	if len(s) != 64 {
		return false
	}
	for _, c := range s {
		if !((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f')) {
			return false
		}
	}
	return true
}

